import React from 'react';
import { cn } from '../../lib/utils';

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      'rounded-xl border border-zinc-200/80 bg-white text-zinc-900 shadow-[0_1px_3px_0_rgba(0,0,0,0.03),0_1px_2px_-1px_rgba(0,0,0,0.03)] transition-colors',
      hoverable && 'hover:border-zinc-300 hover:shadow-[0_2px_6px_0_rgba(0,0,0,0.04)] cursor-pointer',
      className
    )}
    {...props}
  />
));
Card.displayName = 'Card';

